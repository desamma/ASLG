using UnityEngine;
using TMPro;

/// <summary>
/// Example: How to properly use the fixed Crafting System
/// Copy patterns from this file to your own code
/// </summary>
public class CraftingSystemExamples : MonoBehaviour
{
    [SerializeField] private CraftingManager craftingManager;
    [SerializeField] private PlayerInventory playerInventory;
    [SerializeField] private CraftingRecipe testRecipe;

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 1: Basic Craft with Error Handling
    // ?????????????????????????????????????????????????????????????????????????

    public void Example1_BasicCraft()
    {
        if (craftingManager == null || playerInventory == null)
        {
            Debug.LogError("[Example1] Managers not assigned!");
            return;
        }

        // Simple craft call
        bool success = craftingManager.TryCraft(testRecipe, playerInventory, 1);

        if (success)
            Debug.Log($"? Successfully crafted: {testRecipe.DisplayName}");
        else
            Debug.LogWarning($"? Failed to craft: {testRecipe.DisplayName}");
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 2: Craft with Event Listeners (Recommended)
    // ?????????????????????????????????????????????????????????????????????????

    private void OnEnable()
    {
        if (craftingManager == null) return;

        // Subscribe to events
        craftingManager.OnCraftSuccess += OnCraftSuccess;
        craftingManager.OnCraftFailed += OnCraftFailed;
    }

    private void OnDisable()
    {
        if (craftingManager == null) return;

        // Unsubscribe from events (important!)
        craftingManager.OnCraftSuccess -= OnCraftSuccess;
        craftingManager.OnCraftFailed -= OnCraftFailed;
    }

    private void OnCraftSuccess(CraftingRecipe recipe, int quantity)
    {
        Debug.Log($"? Craft Success: {recipe.DisplayName} x{quantity}");
        // Update UI here
        // Play success sound
        // Show feedback animation
    }

    private void OnCraftFailed(CraftingRecipe recipe, string reason)
    {
        Debug.LogWarning($"? Craft Failed: {reason}");
        // Show error message to player
        // Play failure sound
        // Highlight missing materials
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 3: Craft with Multiplier (Batch Crafting)
    // ?????????????????????????????????????????????????????????????????????????

    public void Example3_BatchCraft(int quantity)
    {
        // Validate quantity first
        if (quantity <= 0)
        {
            Debug.LogWarning("[Example3] Quantity must be > 0");
            return;
        }

        // ? New validation: multiplier is checked inside TryCraft
        bool success = craftingManager.TryCraft(testRecipe, playerInventory, quantity);

        if (success)
            Debug.Log($"? Batch crafted: {testRecipe.DisplayName} x{quantity}");
        else
            Debug.LogWarning($"? Batch craft failed for {testRecipe.DisplayName}");
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 4: Pre-check Before Crafting (UI Button Enable/Disable)
    // ?????????????????????????????????????????????????????????????????????????

    public bool CanCraftRecipe(CraftingRecipe recipe, int multiplier = 1)
    {
        // Pre-validation checks
        if (recipe == null)
        {
            Debug.LogWarning("[CanCraftRecipe] Recipe is null");
            return false;
        }

        if (playerInventory == null)
        {
            Debug.LogWarning("[CanCraftRecipe] Inventory is null");
            return false;
        }

        if (multiplier <= 0)
        {
            Debug.LogWarning("[CanCraftRecipe] Multiplier must be > 0");
            return false;
        }

        if (recipe.resultItem == null)
        {
            Debug.LogWarning("[CanCraftRecipe] Recipe result item is null");
            return false;
        }

        // Check materials
        if (!recipe.CanCraft(playerInventory, multiplier))
        {
            Debug.Log("[CanCraftRecipe] Not enough materials");
            return false;
        }

        return true;
    }

    // Usage in UI button:
    public void OnCraftButtonClicked()
    {
        if (!CanCraftRecipe(testRecipe, 1))
        {
            Debug.Log("Cannot craft - button should be disabled");
            return;
        }

        craftingManager.TryCraft(testRecipe, playerInventory, 1);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 5: Using StatRowUI Properly
    // ?????????????????????????????????????????????????????????????????????????

    public void Example5_DisplayStats(StatRowUI statRowUI, StatBonus statBonus)
    {
        if (statRowUI == null)
        {
            Debug.LogError("[Example5] StatRowUI is null!");
            return;
        }

        if (statBonus == null)
        {
            Debug.LogError("[Example5] StatBonus is null!");
            return;
        }

        // ? StatRowUI.Setup now handles:
        // - Null/empty statName ? Fallback to "UNKNOWN"
        // - Proper number formatting (F1 decimal)
        // - Correct color based on value (positive/negative/zero)
        statRowUI.Setup(statBonus.statName, statBonus.value);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 6: Using MaterialRowUI Properly
    // ?????????????????????????????????????????????????????????????????????????

    public void Example6_DisplayMaterial(MaterialRowUI materialRowUI, ItemData itemData, int required)
    {
        if (materialRowUI == null)
        {
            Debug.LogError("[Example6] MaterialRowUI is null!");
            return;
        }

        if (itemData == null)
        {
            Debug.LogError("[Example6] ItemData is null!");
            return;
        }

        if (required <= 0)
        {
            Debug.LogWarning("[Example6] Required amount must be > 0");
            return;
        }

        // Get current inventory amount
        int currentHave = playerInventory.GetItemCount(itemData);

        // ? MaterialRowUI.Setup now handles:
        // - Null item validation
        // - Amount validation (required > 0, currentHave ? 0)
        // - Correct color (green = enough, red = not enough)
        // - Check mark display
        materialRowUI.Setup(itemData, required, currentHave);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 7: Proper Event Flow
    // ?????????????????????????????????????????????????????????????????????????

    public void Example7_CompleteFlow(CraftingRecipe recipe, int quantity)
    {
        Debug.Log($"[Example7] Starting craft: {recipe.DisplayName} x{quantity}");

        // Step 1: Pre-check
        if (!CanCraftRecipe(recipe, quantity))
        {
            Debug.Log("[Example7] Pre-check failed - early exit");
            return;
        }

        // Step 2: Attempt craft
        Debug.Log("[Example7] Pre-check passed - calling TryCraft");
        bool success = craftingManager.TryCraft(recipe, playerInventory, quantity);

        // Step 3: Events will fire (OnCraftSuccess or OnCraftFailed)
        // Step 4: UI updates via event listeners
        Debug.Log($"[Example7] TryCraft returned: {success}");
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 8: Error Handling Patterns
    // ?????????????????????????????????????????????????????????????????????????

    public void Example8_ErrorHandling()
    {
        // Pattern 1: Null coalescing checks
        var mgr = craftingManager ?? throw new System.ArgumentNullException(nameof(craftingManager));
        var inv = playerInventory ?? throw new System.ArgumentNullException(nameof(playerInventory));

        // Pattern 2: Guard clauses
        if (testRecipe == null)
        {
            Debug.LogError("Recipe not assigned!");
            return;
        }

        // Pattern 3: Explicit validation
        if (testRecipe.resultItem == null)
        {
            Debug.LogError($"Recipe {testRecipe.name} has null result item!");
            return;
        }

        // Pattern 4: Safe casting + null check
        CraftingManager instance = CraftingManager.Instance;
        if (instance == null)
        {
            Debug.LogError("CraftingManager.Instance is null!");
            return;
        }

        Debug.Log("All validations passed - safe to proceed");
    }

    // ?????????????????????????????????????????????????????????????????????????
    // ? EXAMPLE 9: Debug Output Patterns
    // ?????????????????????????????????????????????????????????????????????????

    public void Example9_Debugging()
    {
        Debug.Log($"=== Crafting Debug Info ===");
        Debug.Log($"CraftingManager: {(craftingManager != null ? "? Assigned" : "? Missing")}");
        Debug.Log($"PlayerInventory: {(playerInventory != null ? "? Assigned" : "? Missing")}");
        Debug.Log($"Test Recipe: {(testRecipe != null ? "? Assigned" : "? Missing")}");

        if (testRecipe != null)
        {
            Debug.Log($"Recipe Name: {testRecipe.DisplayName}");
            Debug.Log($"Recipe Result: {testRecipe.resultItem?.itemName ?? "NULL"}");
            Debug.Log($"Recipe Ingredients: {testRecipe.ingredients.Count}");

            foreach (var ing in testRecipe.ingredients)
            {
                Debug.Log($"  - {ing.item?.itemName ?? "NULL"} x{ing.amount}");
            }
        }

        if (playerInventory != null)
        {
            Debug.Log($"Inventory Slots: {playerInventory.Entries.Count} / {playerInventory.maxSlots}");
            foreach (var entry in playerInventory.Entries)
            {
                Debug.Log($"  - {entry.item?.itemName ?? "NULL"} x{entry.quantity}");
            }
        }
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Test Methods - Add to your test button
