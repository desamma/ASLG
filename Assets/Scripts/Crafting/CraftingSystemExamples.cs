    [ContextMenu("Test/Example 1 - Basic Craft")]
    private void Test_Example1() => Example1_BasicCraft();

    [ContextMenu("Test/Example 3 - Batch Craft")]
    private void Test_Example3() => Example3_BatchCraft(5);

    [ContextMenu("Test/Example 4 - Can Craft Check")]
    private void Test_Example4() => Debug.Log($"Can craft: {CanCraftRecipe(testRecipe, 1)}");

    [ContextMenu("Test/Example 9 - Debug Info")]
    private void Test_Example9() => Example9_Debugging();
}

/// <summary>
/// Anti-Patterns: Don't do this!
/// </summary>
public class CraftingAntiPatterns
{
    public CraftingManager craftingManager;
    public PlayerInventory playerInventory;

    // ? ANTI-PATTERN 1: No null checks
    public void BadExample1()
    {
        craftingManager.TryCraft(null, playerInventory, 1); // Can crash!
    }

    // ? ANTI-PATTERN 2: Ignoring return value
    public void BadExample2(CraftingRecipe recipe)
    {
        craftingManager.TryCraft(recipe, playerInventory, 1); // What if it fails?
    }

    // ? ANTI-PATTERN 3: Not unsubscribing from events
    public void BadExample3()
    {
        craftingManager.OnCraftSuccess += (r, q) => { };
        // If this script is destroyed, event subscription leaks!
    }

    // ? ANTI-PATTERN 4: Invalid multiplier
    public void BadExample4()
    {
        craftingManager.TryCraft(null, playerInventory, 0); // multiplier = 0 is invalid
    }

    // ? ANTI-PATTERN 5: Silent failures
    public void BadExample5(CraftingRecipe recipe)
    {
        bool success = craftingManager.TryCraft(recipe, playerInventory, 1);
        // No logging or user feedback
    }

    // ? CORRECTED VERSIONS

    // ? GOOD EXAMPLE 1: Proper null checks
    public void GoodExample1(CraftingRecipe recipe)
    {
        if (recipe == null)
        {
            Debug.LogWarning("Recipe is null!");
            return;
        }
        craftingManager.TryCraft(recipe, playerInventory, 1);
    }

    // ? GOOD EXAMPLE 2: Check return value
    public void GoodExample2(CraftingRecipe recipe)
    {
        if (craftingManager.TryCraft(recipe, playerInventory, 1))
            Debug.Log("Craft successful!");
        else
            Debug.LogWarning("Craft failed!");
    }

    // ? GOOD EXAMPLE 3: Proper unsubscribe
    private void OnEnable()
    {
        craftingManager.OnCraftSuccess += OnSuccess;
    }

    private void OnDisable()
    {
        craftingManager.OnCraftSuccess -= OnSuccess;
    }

    private void OnSuccess(CraftingRecipe recipe, int qty) { }

    // ? GOOD EXAMPLE 4: Valid multiplier
    public void GoodExample4(CraftingRecipe recipe, int quantity)
    {
        if (quantity <= 0)
        {
            Debug.LogWarning("Quantity must be > 0");
            return;
        }
        craftingManager.TryCraft(recipe, playerInventory, quantity);
    }

    // ? GOOD EXAMPLE 5: Proper feedback
    public void GoodExample5(CraftingRecipe recipe)
    {
        bool success = craftingManager.TryCraft(recipe, playerInventory, 1);
        if (success)
            Debug.Log($"? Crafted: {recipe.DisplayName}");
        else
            Debug.LogWarning($"? Failed to craft: {recipe.DisplayName}");
    }
}
